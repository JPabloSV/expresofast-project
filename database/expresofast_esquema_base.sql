CREATE PROCEDURE [dbo].[SP_RESUMEN_METRICAS_ENVIOS]
AS
BEGIN
    SET NOCOUNT ON;

    SELECT
        estado_envio,
        COUNT(*)   AS total_envios,
        SUM(costo) AS costo_total
    FROM dbo.Envio
    GROUP BY estado_envio;
END
